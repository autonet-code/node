def probe_ollama() -> List[str]:
    """Installed ollama model ids, or [] when the server is unreachable."""
    import httpx
    try:
        r = httpx.get(f"{OLLAMA_URL.rstrip('/')}/api/tags", timeout=10.0)
        r.raise_for_status()
        return [m.get("name", "") for m in (r.json().get("models") or [])
                if m.get("name")]
    except Exception as exc:  # noqa: BLE001
        log(f"ollama probe failed at {OLLAMA_URL}: {exc}")
        return []


def maybe_start_ollama() -> Optional[subprocess.Popen]:
    """Start `ollama serve` if the binary is around and nothing is listening.

    Returns the process we started (so we tear it down) or None when ollama was
    already up / not installed — never kill a server the user was already using.
    """
    exe = shutil.which("ollama")
    if not exe:
        return None
    log(f"starting ollama serve ({exe})…")
    proc = subprocess.Popen(
        [exe, "serve"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        creationflags=(subprocess.CREATE_NEW_PROCESS_GROUP
                       if os.name == "nt" else 0),
    )
    deadline = time.time() + 30.0
    while time.time() < deadline:
        if probe_ollama():
            return proc
        time.sleep(1.0)
    kill_proc_tree(proc)
    return None


def warm_model(model: str) -> bool:
    """Pre-load the model so the first PAID call isn't also the cold load.

    Not a shortcut: the paid call still goes through the whole rail. This only
    moves ~20s of GGUF load out of the timed cross-daemon hop, the same thing
    any real provider's daemon does by keeping a model resident.
    """
    import httpx
    try:
        r = httpx.post(
            f"{OLLAMA_URL.rstrip('/')}/api/chat",
            json={"model": model, "stream": False, "think": False,
                  "messages": [{"role": "user", "content": "hi"}],
                  "options": {"num_predict": 4}},
            timeout=240.0)
        r.raise_for_status()
        return True
    except Exception as exc:  # noqa: BLE001
        log(f"model warm-up failed: {exc}")
        return False



class _SkipStage(Exception):
    """Raised inside a stage body to jump to its end without failing it.

    Used by the split-machine modes: a stage that belongs to the OTHER box has
    already set itself SKIP and has nothing left to do, but the stage bodies are
    long linear blocks and an early `return` would abandon the run. The stage's
    own ``except`` re-raises nothing for this type.
    """


class Stage:
    def __init__(self, num: int, name: str):
        self.num = num
        self.name = name
        self.status = "PENDING"  # PASS | FAIL | SKIP
        self.notes: List[str] = []

    def note(self, k: str, v: Any) -> None:
        self.notes.append(f"{k}={v}")


class Board:
    def __init__(self) -> None:
        self.stages: Dict[int, Stage] = {}

    def stage(self, num: int, name: str) -> Stage:
        s = Stage(num, name)
        self.stages[num] = s
        return s

    def render(self) -> str:
        lines = ["", "=" * 74,
                 "  CROSS-DAEMON REAL-INFERENCE E2E — SCOREBOARD", "=" * 74]
        for num in sorted(self.stages):
            s = self.stages[num]
            mark = {"PASS": "PASS", "FAIL": "FAIL", "SKIP": "SKIP",
                    "PENDING": "----"}[s.status]
            lines.append(f"  [{mark}] Stage {s.num} — {s.name}")
            for n in s.notes:
                lines.append(f"           {n}")
        lines.append("=" * 74)
        n_pass = sum(1 for s in self.stages.values() if s.status == "PASS")
        n_fail = sum(1 for s in self.stages.values() if s.status == "FAIL")
        n_skip = sum(1 for s in self.stages.values() if s.status == "SKIP")
        lines.append(f"  {n_pass} PASS / {n_fail} FAIL / {n_skip} SKIP")
        lines.append("=" * 74)
        return "\n".join(lines)


def _safe(msg: str) -> str:
    """Strip anything the console codec can't encode.

    Windows consoles default to cp1252; a daemon log tail carrying a rich-console
    box-drawing char or an em dash crashes ``print`` with a UnicodeEncodeError —
    which would then mask the real failure we were trying to report.
    """
    enc = getattr(sys.stdout, "encoding", None) or "utf-8"
    return msg.encode(enc, errors="replace").decode(enc, errors="replace")


def log(msg: str) -> None:
    print(_safe(f"[e2e] {msg}"), flush=True)


def step(msg: str) -> None:
    print(_safe(f"  PASS  {msg}"), flush=True)


